def _expect(request: httpx.Request, row: tuple[Any, ...]) -> None:
    _, _, _, _, verb, path, query, body, idem = row
    assert request.method == verb
    assert request.url.raw_path.decode().split("?")[0] == path
    assert dict(request.url.params) == query
    if body is None:
        assert request.content == b""
    else:
        assert json.loads(request.content) == body
    assert (request.headers.get("idempotency-key") == "idem-1") is idem


def _target(client: Any, row: tuple[Any, ...]) -> Any:
    return getattr(reduce(getattr, row[0].split("."), client), row[1])


